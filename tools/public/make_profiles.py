"""Bundle the ground-truth calibrations of the converted public scenes into the extension (extension/calibs/).

    .venv/bin/python tools/public/make_profiles.py [~/public-data/cvat-upload]

Every <dir>/gt/calib-gt.json written by nuscenes_to_cvat.py / kitti_to_cvat.py becomes extension/calibs/<id>.json,
and extension/calibs/index.json lists them with a pattern on the CVAT task name: name the task after the scene
(e.g. "nuscenes scene-0061", "kitti 2011_09_26_drive_0005") and the extension picks its calibration by itself.
Only calibration numbers are bundled (no images / point clouds); each file keeps its "source" (dataset, licence).
"""
import glob, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'extension', 'calibs')


def profile_of(d, calib):
    src = calib.get('source', '')
    if m := re.search(r'(scene-\d{4})', src):
        sc = m.group(1)
        return {'id': f'nuscenes-{sc}', 'name': f'nuScenes {sc}', 'match': f'{sc}|nuscenes[-_ ]?{sc[6:]}',
                'dataset': 'nuScenes v1.0-mini', 'licence': 'CC BY-NC-SA 4.0'}
    if m := re.search(r'(\d{4}_\d{2}_\d{2})_drive_(\d{4})', src):
        day = m.group(1)
        return {'id': f'kitti-{day}', 'name': f'KITTI raw {day}', 'match': f'{day}|kitti',
                'dataset': 'KITTI raw', 'licence': 'CC BY-NC-SA 3.0'}
    raise SystemExit(f'{d}: unknown source "{src}"')


def main(root):
    os.makedirs(OUT, exist_ok=True)
    profiles = {}
    for path in sorted(glob.glob(os.path.join(os.path.expanduser(root), '*', 'gt', 'calib-gt.json'))):
        calib = json.load(open(path))
        p = profile_of(path, calib)
        if p['id'] in profiles:
            continue                                   # e.g. keyframe and sweep conversions of one scene
        p['file'] = p['id'] + '.json'
        json.dump(calib, open(os.path.join(OUT, p['file']), 'w'), indent=1)
        profiles[p['id']] = p
    index = {'note': 'Calibrations bundled with the extension, picked by CVAT task name (match = regex, case-insensitive). '
                     'Generated by tools/public/make_profiles.py.',
             'profiles': sorted(profiles.values(), key=lambda p: p['id'])}
    json.dump(index, open(os.path.join(OUT, 'index.json'), 'w'), indent=1)
    for p in index['profiles']:
        print(f"{p['id']:24s} task name ~ /{p['match']}/i")
    print(f'{len(profiles)} profiles -> {os.path.normpath(OUT)}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '~/public-data/cvat-upload')
